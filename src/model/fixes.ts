import type { Attribute, Entity, Relationship, SchemaModel, SchemaPatchOperation } from './types';
import type { ReviewFix } from './rules';

export interface ReviewFixPreview {
  title: string;
  summary: string;
  operations: SchemaPatchOperation[];
  before: string[];
  after: string[];
}

function makeId(prefix: string): string {
  return `${prefix}-${crypto.randomUUID()}`;
}

function cloneAttribute(attribute: Attribute, id = makeId('attribute')): Attribute {
  return {
    ...structuredClone(attribute),
    id,
    ...(attribute.children ? { children: attribute.children.map((child) => cloneAttribute(child)) } : {}),
  };
}

function renameForId(name: string): string {
  const safe = name.trim().replace(/[^a-zA-Z0-9_]+/g, '_').replace(/^_+|_+$/g, '').toLowerCase();
  return safe || 'entity';
}

function makeRelationship(from: string, to: string, label: string): Relationship {
  return {
    id: makeId('relationship'), from, to, label,
    fromCardinality: '1', toCardinality: '0..N',
    identifying: true, participation: 'total', attributes: [],
    onDelete: 'CASCADE', onUpdate: 'CASCADE', notes: 'Generated by the deterministic Schema Review fix preview.',
  };
}

function makeAssociation(model: SchemaModel, relationship: Relationship): { entity: Entity; relationships: Relationship[] } | null {
  const from = model.entities.find((entity) => entity.id === relationship.from);
  const to = model.entities.find((entity) => entity.id === relationship.to);
  if (!from || !to) return null;
  const fromKeys = from.attributes.filter((attribute) => attribute.isPK);
  const toKeys = to.attributes.filter((attribute) => attribute.isPK);
  if (fromKeys.length === 0 || toKeys.length === 0) return null;
  const entityId = makeId('entity');
  const copyKey = (attribute: Attribute, owner: Entity): Attribute => ({
    id: makeId('attribute'),
    name: `${renameForId(owner.name)}_${attribute.name}`,
    dataType: attribute.dataType,
    isPK: true,
    isFK: true,
    isUnique: true,
    isNullable: false,
    isIndexed: true,
    kind: 'simple',
    foreignKeyRef: { entityId: owner.id, attributeId: attribute.id },
    notes: `Composite junction key; references ${owner.name}.${attribute.name}.`,
  });
  const attributes = [...fromKeys.map((attribute) => copyKey(attribute, from)), ...toKeys.map((attribute) => copyKey(attribute, to)), ...relationship.attributes.map((attribute) => cloneAttribute(attribute))];
  const entity: Entity = {
    id: entityId,
    name: `${from.name}${to.name}Link`,
    kind: 'associative',
    attributes,
    notes: `Deterministic junction generated from the ${relationship.label || 'M:N'} relationship. Review naming and constraints before deployment.`,
  };
  return { entity, relationships: [makeRelationship(from.id, entityId, relationship.label || 'has link'), makeRelationship(to.id, entityId, relationship.label || 'has link')] };
}

export function buildReviewFixPreview(model: SchemaModel, fix: ReviewFix): ReviewFixPreview | null {
  if (fix.kind === 'mark-derived-virtual') {
    const entity = model.entities.find((item) => item.id === fix.entityId);
    const attribute = entity?.attributes.find((item) => item.id === fix.attributeId);
    if (!entity || !attribute || attribute.kind !== 'derived' || attribute.isStored !== true) return null;
    return {
      title: `Keep ${entity.name}.${attribute.name} virtual`,
      summary: 'Clear the stored flag. The derivation formula and all other metadata remain unchanged.',
      operations: [{ op: 'attribute.update', entityId: entity.id, attributeId: attribute.id, changes: { isStored: false } }],
      before: [`${attribute.name}: derived, stored`], after: [`${attribute.name}: derived, virtual`],
    };
  }
  if (fix.kind === 'index-foreign-key') {
    const entity = model.entities.find((item) => item.id === fix.entityId);
    const attribute = entity?.attributes.find((item) => item.id === fix.attributeId);
    if (!entity || !attribute || !attribute.isFK || attribute.isPK || attribute.isUnique || attribute.isIndexed) return null;
    return {
      title: `Mark ${entity.name}.${attribute.name} as indexed`,
      summary: 'Set index metadata in the model. Review the generated DDL for the target database before applying it.',
      operations: [{ op: 'attribute.update', entityId: entity.id, attributeId: attribute.id, changes: { isIndexed: true } }],
      before: [`${attribute.name}: foreign key, no explicit index`], after: [`${attribute.name}: foreign key, indexed`],
    };
  }
  if (fix.kind === 'normalize-multivalued') {
    const entity = model.entities.find((item) => item.id === fix.entityId);
    const attribute = entity?.attributes.find((item) => item.id === fix.attributeId);
    const keys = entity?.attributes.filter((item) => item.isPK) ?? [];
    if (!entity || !attribute || attribute.kind !== 'multivalued' || keys.length === 0) return null;
    const childId = makeId('entity');
    const ownerKeyAttributes: Attribute[] = keys.map((key) => ({
      id: makeId('attribute'), name: key.name, dataType: key.dataType, isPK: true, isFK: true, isUnique: true,
      isNullable: false, isIndexed: true, kind: 'simple', foreignKeyRef: { entityId: entity.id, attributeId: key.id }, notes: `References ${entity.name}.${key.name}.`,
    }));
    const valueAttributes = attribute.children?.length
      ? attribute.children.map((child) => ({ ...cloneAttribute(child), isPK: true, isFK: false, isUnique: false, isNullable: false, foreignKeyRef: undefined, kind: 'simple' as const }))
      : [{ id: makeId('attribute'), name: attribute.name.replace(/s$/, '') || 'value', dataType: attribute.dataType, isPK: true, isFK: false, isUnique: false, isNullable: false, kind: 'simple' as const, notes: 'A multivalued value is unique within its owner key.' }];
    if (!attribute.children?.length) valueAttributes[0]!.isPK = true;
    const child: Entity = {
      id: childId,
      name: `${entity.name}${attribute.name.charAt(0).toUpperCase()}${attribute.name.slice(1)}`,
      kind: 'associative', attributes: [...ownerKeyAttributes, ...valueAttributes],
      notes: `Normalized from ${entity.name}.${attribute.name}.`,
    };
    const relation = makeRelationship(entity.id, child.id, attribute.name);
    return {
      title: `Normalize ${entity.name}.${attribute.name}`,
      summary: 'Move the multivalued field to a child associative entity. The owner key becomes a foreign key; declared components or a scalar value are preserved.',
      operations: [
        { op: 'attribute.delete', entityId: entity.id, attributeId: attribute.id },
        { op: 'entity.add', entity: child },
        { op: 'relationship.add', relationship: relation },
      ],
      before: [`${entity.name}.${attribute.name}: multivalued attribute`], after: [`${child.name}: child relation keyed by ${keys.map((key) => key.name).join(' + ')} and its value fields`],
    };
  }
  const relationship = model.relationships.find((item) => item.id === fix.relationshipId);
  if (!relationship || (relationship.fromCardinality !== 'M:N' && relationship.toCardinality !== 'M:N')) return null;
  const association = makeAssociation(model, relationship);
  if (!association) return null;
  return {
    title: `Create ${association.entity.name} junction`,
    summary: 'Replace the direct M:N link with an associative entity using both endpoint primary keys. The relationship attributes are carried onto the junction. Review generated names and cardinalities.',
    operations: [
      { op: 'relationship.delete', relationshipId: relationship.id },
      { op: 'entity.add', entity: association.entity },
      ...association.relationships.map((item) => ({ op: 'relationship.add' as const, relationship: item })),
    ],
    before: [`${relationship.label || 'Unnamed'}: direct many-to-many relationship`], after: [`${association.entity.name}: associative junction with ${association.entity.attributes.length} attributes and two endpoint relationships`],
  };
}
